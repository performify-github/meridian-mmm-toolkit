#!/usr/bin/env python3
"""Render the model-input views for BigQuery from the config's `sql` block.

    python3 mmm/sql_views.py --config B/mmm.yaml            # writes B/sql/*.sql
    bq query --use_legacy_sql=false < B/sql/<dataset>.vw_mmm_campaign_channel.sql
    bq query --use_legacy_sql=false < B/sql/<dataset>.vw_mmm_weekly_geo.sql

Three files:
- `vw_mmm_campaign_channel`: one row per campaign-day, tagged with a channel group and a
  geo. The only place the campaign → channel mapping lives.
- `vw_mmm_weekly_geo`: the table the model reads: one row per geo per week, with the KPIs,
  spend and impressions per channel, the controls and the guardrail columns.
- `qa_campaign_channel_map`: a review list of every campaign above `qa_min_spend` and the
  group it landed in. Read it once by eye before the first fit.

This covers the common DTC case: a daily ads-by-campaign table and an orders table. Any other
table with the same columns works too (README → The input table). The rendered files are
the source of truth for the views, so commit them with the config.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import config as cfgmod  # noqa: E402


def _q(s: str) -> str:
    if "'" in s:
        raise cfgmod.ConfigError(f"quotes aren't allowed in SQL literals and patterns: {s!r}")
    return f"'{s}'"


def _platform(p) -> str:
    return f"platform = {_q(p)}" if isinstance(p, str) else f"platform IN ({', '.join(_q(x) for x in p)})"


def channel_case(sql: dict) -> str:
    lines = []
    for r in sql["channel_rules"]:
        conds = [_platform(r["platform"])]
        either = []
        if r.get("objectives"):
            either.append(f"objective_type IN ({', '.join(_q(o.lower()) for o in r['objectives'])})")
        if r.get("name_regex"):
            either.append(f"REGEXP_CONTAINS(n, r{_q(r['name_regex'])})")
        if either:
            conds.append(either[0] if len(either) == 1 else f"({' OR '.join(either)})")
        if r.get("exclude_regex"):
            conds.append(f"NOT REGEXP_CONTAINS(n, r{_q(r['exclude_regex'])})")
        lines.append(f"    WHEN {' AND '.join(conds)}\n      THEN {_q(r['group'])}")
    return "  CASE\n" + "\n".join(lines) + "\n    ELSE 'unmapped'\n  END AS channel_group"


def geo_case(sql: dict, field: str, overrides: bool) -> str:
    lines = []
    if overrides:
        for o in sql.get("ads_region_overrides") or []:
            note = f"    -- {o['note']}\n" if o.get("note") else ""
            lines.append(f"{note}    WHEN {field} = {_q(o['region'])} AND REGEXP_CONTAINS(n, r{_q(o['name_regex'])}) "
                         f"THEN {_q(o['geo'])}")
    for region, geo in sql["region_to_geo"].items():
        lines.append(f"    WHEN {field} = {_q(str(region))} THEN {_q(geo)}")
    return "  CASE\n" + "\n".join(lines) + "\n  END AS geo"


def render(conf: cfgmod.Config) -> dict[str, str]:
    c = conf.cfg
    sql = c["sql"]
    if not sql:
        raise cfgmod.ConfigError("the config has no `sql` block")
    if not sql.get("start_week"):
        raise cfgmod.ConfigError("sql.start_week (or data.window.start) is needed for the views")
    ds, wk = sql["dataset"], f"WEEK({c['data']['week_start_day'].upper()})"
    a, o = sql["ads"], sql["orders"]
    ac, oc = a["columns"], o["columns"]
    channels = list(c["channels"])
    controls = list(sql.get("control_groups") or [])
    groups = ", ".join([*channels, *controls])
    view_cc, view_wk = f"{ds}.vw_mmm_campaign_channel", f"{ds}.vw_mmm_weekly_geo"
    sis = ac.get("search_impression_share")
    eligible = ("IF(search_impression_share > 0,\n     impressions / GREATEST(search_impression_share, 0.1),\n"
                "     impressions)" if sis else "impressions")
    sale = sql.get("sale_campaign_regex")
    rule_note = "\n".join(f"     {r['group']:<16}{', '.join([r['platform']] if isinstance(r['platform'], str) else r['platform'])}"
                          + (f" · objective {', '.join(r['objectives'])}" if r.get("objectives") else "")
                          + (" · name pattern" if r.get("name_regex") else "")
                          + (" · minus exclusions" if r.get("exclude_regex") else "")
                          for r in sql["channel_rules"])

    campaign = f"""/* =======================================================================
   VIEW: {view_cc}
   Generated by mmm/sql_views.py from {conf.path.name} — edit the config, not this file.
   PURPOSE: Daily ads delivery, one row per campaign-day, tagged with the MMM
            channel group and geo. The only place the campaign → channel mapping
            lives: vw_mmm_weekly_geo aggregates this, and qa_campaign_channel_map.sql
            lists it for review.

   CHANNEL RULES (first match wins; patterns run on the upper-cased name):
{rule_note}
     unmapped        anything else — a fit stops if this carries more than
                     {c['guardrails']['max_unmapped_spend_share']:.0%} of spend

   Control groups ({', '.join(controls) or 'none'}) are controls in the model, not media.
======================================================================= */

CREATE OR REPLACE VIEW `{view_cc}` AS

WITH base AS (
  SELECT
    {ac['date']} AS date,
    {ac['platform']} AS platform,
    {ac['campaign_id']} AS campaign_id,
    {ac['campaign_name']} AS campaign_name,
    LOWER(IFNULL({ac['objective']}, 'unknown')) AS objective_type,
    {ac['region']} AS region,
    UPPER({ac['campaign_name']}) AS n,
    IFNULL({ac['spend']}, 0) AS spend,
    IFNULL({ac['impressions']}, 0) AS impressions,
    IFNULL({ac['clicks']}, 0) AS clicks{f''',
    {sis} AS search_impression_share''' if sis else ''}
  FROM `{a['table']}`
)

SELECT
  date,
{geo_case(sql, 'region', overrides=True)},
  platform,
  campaign_id,
  campaign_name,
  objective_type,
{channel_case(sql)},
  -- Sale / promotion campaigns, read from the name (feeds the sale_campaign_live control)
  {f"REGEXP_CONTAINS(n, r{_q(sale)})" if sale else "FALSE"} AS is_sale_campaign,
  spend,
  impressions,
  clicks,
  -- Eligible impressions ≈ the query volume a search campaign could have shown on.
  -- Impression share below 10% is reported as ~0.0999, so it is floored at 0.1.
  {eligible} AS eligible_impressions
FROM base;
"""

    sel_media = []
    for ch in channels:
        sel_media.append(f"    SUM(IF(channel_group = {_q(ch)}, spend, 0)) AS {conf.spend_col(ch)}")
    for ch in channels:
        sel_media.append(f"    SUM(IF(channel_group = {_q(ch)}, impressions, 0)) AS {conf.media_col(ch)}")
    for g in controls:
        sel_media += [f"    SUM(IF(channel_group = {_q(g)}, spend, 0)) AS {g}_spend",
                      f"    SUM(IF(channel_group = {_q(g)}, clicks, 0)) AS {g}_clicks",
                      f"    SUM(IF(channel_group = {_q(g)}, impressions, 0)) AS {g}_impressions",
                      f"    SUM(IF(channel_group = {_q(g)}, eligible_impressions, 0)) AS {g}_eligible_impressions"]
    sel_media += ["    SUM(IF(channel_group = 'unmapped', spend, 0)) AS unmapped_spend",
                  "    SUM(IF(is_sale_campaign, spend, 0)) AS sale_campaign_spend"]
    out_media = [f"  IFNULL(m.{conf.spend_col(ch)}, 0) AS {conf.spend_col(ch)}," for ch in channels]
    out_media += [f"  IFNULL(m.{conf.media_col(ch)}, 0) AS {conf.media_col(ch)}," for ch in channels]
    out_ctrl = [f"  IFNULL(m.{g}_{k}, 0) AS {g}_{k}," for g in controls
                for k in ("spend", "clicks", "impressions", "eligible_impressions")]
    trends = sql.get("trends_table")
    geos = ", ".join(_q(g) for g in c["geos"])

    weekly = f"""/* =======================================================================
   VIEW: {view_wk}
   Generated by mmm/sql_views.py from {conf.path.name} — edit the config, not this file.
   PURPOSE: The model input: one row per geo × week ({c['data']['week_start_day'].title()} start),
            {sql['start_week']} → the last complete week.

   KPI        orders            orders in `{o['table']}`{f" where {o['where']}" if o.get('where') else ''}
              new_customers     orders that are the customer's FIRST order ever (first order
                                per customer key over the whole table, not a "new" flag)
              revenue           {oc['revenue']}
   MEDIA      spend / impressions per channel group ({', '.join(channels)})
   CONTROLS   <group>_clicks / _impressions / _eligible_impressions for each control
              group ({', '.join(controls) or 'none'}): demand-control candidates
              discount_depth = discounts ÷ (subtotal + discounts)
              sale_campaign_live = any spend that week on a sale campaign
              brand_trends_index = Google Trends brand topic (mmm/trends.py){'' if trends else ' — not configured'}
   GUARDRAILS unmapped_spend, unmapped_geo_spend_all_geos (a fit stops on these)
   Calendar flags and population are added in the notebook.
======================================================================= */

CREATE OR REPLACE VIEW `{view_wk}` AS

WITH
params AS (
  SELECT
    DATE {_q(sql['start_week'])} AS start_week,
    DATE_SUB(DATE_TRUNC(CURRENT_DATE({_q(sql.get('timezone') or 'UTC')}), {wk}), INTERVAL 7 DAY) AS last_week
),

spine AS (
  SELECT week_start, geo
  FROM params,
    UNNEST(GENERATE_DATE_ARRAY(start_week, last_week, INTERVAL 7 DAY)) AS week_start,
    UNNEST([{geos}]) AS geo
),

/* ── Orders ─────────────────────────────────────────────────────────────── */
orders AS (
  SELECT
    {oc['order_id']} AS order_id,
    {oc['order_date']} AS order_date,
    {oc['created_at']} AS created_at,
{geo_case(sql, oc['region'], overrides=False)},
    {oc['customer_key']} AS customer_key,
    {oc['revenue']} AS revenue,
    {oc['discounts']} AS discounts,
    {oc['subtotal']} AS subtotal
  FROM `{o['table']}`{f'''
  WHERE {o['where']}''' if o.get('where') else ''}
),

orders_ranked AS (
  SELECT
    *,
    ROW_NUMBER() OVER (PARTITION BY customer_key ORDER BY created_at, order_id) AS customer_order_n
  FROM orders
),

orders_weekly AS (
  SELECT
    DATE_TRUNC(order_date, {wk}) AS week_start,
    geo,
    COUNT(*) AS orders,
    COUNTIF(customer_order_n = 1 AND customer_key IS NOT NULL) AS new_customers,
    SUM(revenue) AS revenue,
    SUM(IF(customer_order_n = 1 AND customer_key IS NOT NULL, revenue, 0)) AS new_customer_revenue,
    SAFE_DIVIDE(SUM(discounts), SUM(subtotal) + SUM(discounts)) AS discount_depth,
    SAFE_DIVIDE(COUNTIF(discounts > 0), COUNT(*)) AS discounted_order_share
  FROM orders_ranked
  WHERE geo IS NOT NULL
  GROUP BY 1, 2
),

/* ── Media + control groups ([{groups}]) ── */
media_weekly AS (
  SELECT
    DATE_TRUNC(date, {wk}) AS week_start,
    geo,
{(","+chr(10)).join(sel_media)}
  FROM `{view_cc}`
  WHERE geo IS NOT NULL
  GROUP BY 1, 2
),

-- Spend whose region doesn't map to a geo (surfaced, never silently lost)
unmapped_geo AS (
  SELECT DATE_TRUNC(date, {wk}) AS week_start, SUM(spend) AS spend
  FROM `{view_cc}`
  WHERE geo IS NULL
  GROUP BY 1
)

SELECT
  s.week_start,
  s.geo,
  -- KPIs
  IFNULL(o.orders, 0) AS orders,
  IFNULL(o.new_customers, 0) AS new_customers,
  IFNULL(o.revenue, 0) AS revenue,
  IFNULL(o.new_customer_revenue, 0) AS new_customer_revenue,
  -- Paid media
{chr(10).join(out_media)}
  -- Controls
{chr(10).join(out_ctrl)}
  o.discount_depth,
  o.discounted_order_share,
  IFNULL(m.sale_campaign_spend, 0) AS sale_campaign_spend,
  IF(IFNULL(m.sale_campaign_spend, 0) > 0, 1, 0) AS sale_campaign_live,
  {'t.trends_index' if trends else 'CAST(NULL AS FLOAT64)'} AS brand_trends_index,
  -- Guardrails (the notebook asserts on these)
  IFNULL(m.unmapped_spend, 0) AS unmapped_spend,
  IFNULL(u.spend, 0) AS unmapped_geo_spend_all_geos
FROM spine s
LEFT JOIN orders_weekly o USING (week_start, geo)
LEFT JOIN media_weekly m USING (week_start, geo)
LEFT JOIN unmapped_geo u USING (week_start){f'''
LEFT JOIN `{trends}` t USING (week_start, geo)''' if trends else ''};
"""

    qa = f"""-- Review list for the channel mapping ({view_cc}).
-- Generated by mmm/sql_views.py from {conf.path.name}.
-- Every campaign with at least {sql.get('qa_min_spend', 500)} spend in the model window, the group it was given,
-- and whether it counts as a sale campaign. Read it once before the first fit; campaigns
-- added later follow the same rules, and a fit stops if 'unmapped' carries too much spend.

SELECT
  channel_group,
  platform,
  objective_type,
  campaign_name,
  STRING_AGG(DISTINCT IFNULL(geo, 'NULL-GEO') ORDER BY IFNULL(geo, 'NULL-GEO')) AS geos,
  LOGICAL_OR(is_sale_campaign) AS sale_flag,
  ROUND(SUM(spend)) AS spend,
  MIN(date) AS first_day,
  MAX(date) AS last_day
FROM `{view_cc}`
WHERE date >= {_q(sql['start_week'])}
GROUP BY 1, 2, 3, 4
HAVING spend >= {sql.get('qa_min_spend', 500)}
ORDER BY channel_group, spend DESC;
"""
    return {f"{ds.split('.')[-1]}.vw_mmm_campaign_channel.sql": campaign,
            f"{ds.split('.')[-1]}.vw_mmm_weekly_geo.sql": weekly,
            "qa_campaign_channel_map.sql": qa}


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--config", required=True)
    p.add_argument("--out", help="default: sql/ next to the config")
    a = p.parse_args()
    try:
        conf = cfgmod.load(a.config)
        files = render(conf)
    except cfgmod.ConfigError as e:
        sys.exit(str(e))
    out = pathlib.Path(a.out) if a.out else conf.dir / "sql"
    out.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out / name).write_text(text)
        print(out / name)
    print("\nCreate the views (campaign view first):")
    for name in list(files)[:2]:
        print(f"  bq query --use_legacy_sql=false < {out / name}")


if __name__ == "__main__":
    main()
