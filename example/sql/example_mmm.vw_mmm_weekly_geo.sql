/* =======================================================================
   VIEW: your-gcp-project.example_mmm.vw_mmm_weekly_geo
   Generated by mmm/sql_views.py from mmm.yaml — edit the config, not this file.
   PURPOSE: The model input: one row per geo × week (Monday start),
            2023-01-02 → the last complete week.

   KPI        orders            orders in `your-gcp-project.example.fact_orders` where revenue_excl_shipping > 0
              new_customers     orders that are the customer's FIRST order ever (first order
                                per customer key over the whole table, not a "new" flag)
              revenue           revenue_excl_shipping
   MEDIA      spend / impressions per channel group (google_convert, google_upper, meta_convert, meta_upper)
   CONTROLS   <group>_clicks / _impressions / _eligible_impressions for each control
              group (brand_search): demand-control candidates
              discount_depth = discounts ÷ (subtotal + discounts)
              sale_campaign_live = any spend that week on a sale campaign
              brand_trends_index = Google Trends brand topic (mmm/trends.py)
   GUARDRAILS unmapped_spend, unmapped_geo_spend_all_geos (a fit stops on these)
   Calendar flags and population are added in the notebook.
======================================================================= */

CREATE OR REPLACE VIEW `your-gcp-project.example_mmm.vw_mmm_weekly_geo` AS

WITH
params AS (
  SELECT
    DATE '2023-01-02' AS start_week,
    DATE_SUB(DATE_TRUNC(CURRENT_DATE('Europe/London'), WEEK(MONDAY)), INTERVAL 7 DAY) AS last_week
),

spine AS (
  SELECT week_start, geo
  FROM params,
    UNNEST(GENERATE_DATE_ARRAY(start_week, last_week, INTERVAL 7 DAY)) AS week_start,
    UNNEST(['UK', 'DE', 'FR', 'NORDICS']) AS geo
),

/* ── Orders ─────────────────────────────────────────────────────────────── */
orders AS (
  SELECT
    order_id AS order_id,
    order_date AS order_date,
    created_at AS created_at,
  CASE
    WHEN market_region = 'GB' THEN 'UK'
    WHEN market_region = 'DE' THEN 'DE'
    WHEN market_region = 'FR' THEN 'FR'
    WHEN market_region = 'SE' THEN 'NORDICS'
    WHEN market_region = 'DK' THEN 'NORDICS'
    WHEN market_region = 'False' THEN 'NORDICS'
    WHEN market_region = 'FI' THEN 'NORDICS'
  END AS geo,
    COALESCE(TO_HEX(hashed_email), CAST(customer_id AS STRING)) AS customer_key,
    revenue_excl_shipping AS revenue,
    total_discounts AS discounts,
    subtotal_price AS subtotal
  FROM `your-gcp-project.example.fact_orders`
  WHERE revenue_excl_shipping > 0
),

orders_ranked AS (
  SELECT
    *,
    ROW_NUMBER() OVER (PARTITION BY customer_key ORDER BY created_at, order_id) AS customer_order_n
  FROM orders
),

orders_weekly AS (
  SELECT
    DATE_TRUNC(order_date, WEEK(MONDAY)) AS week_start,
    geo,
    COUNT(*) AS orders,
    COUNTIF(customer_order_n = 1 AND customer_key IS NOT NULL) AS new_customers,
    SUM(revenue) AS revenue,
    SUM(IF(customer_order_n = 1 AND customer_key IS NOT NULL, revenue, 0)) AS new_customer_revenue,
    SAFE_DIVIDE(SUM(discounts), SUM(subtotal) + SUM(discounts)) AS discount_depth,
    SAFE_DIVIDE(COUNTIF(discounts > 0), COUNT(*)) AS discounted_order_share
  FROM orders_ranked
  WHERE geo IS NOT NULL
  GROUP BY 1, 2
),

/* ── Media + control groups ([google_convert, google_upper, meta_convert, meta_upper, brand_search]) ── */
media_weekly AS (
  SELECT
    DATE_TRUNC(date, WEEK(MONDAY)) AS week_start,
    geo,
    SUM(IF(channel_group = 'google_convert', spend, 0)) AS spend_google_convert,
    SUM(IF(channel_group = 'google_upper', spend, 0)) AS spend_google_upper,
    SUM(IF(channel_group = 'meta_convert', spend, 0)) AS spend_meta_convert,
    SUM(IF(channel_group = 'meta_upper', spend, 0)) AS spend_meta_upper,
    SUM(IF(channel_group = 'google_convert', impressions, 0)) AS impressions_google_convert,
    SUM(IF(channel_group = 'google_upper', impressions, 0)) AS impressions_google_upper,
    SUM(IF(channel_group = 'meta_convert', impressions, 0)) AS impressions_meta_convert,
    SUM(IF(channel_group = 'meta_upper', impressions, 0)) AS impressions_meta_upper,
    SUM(IF(channel_group = 'brand_search', spend, 0)) AS brand_search_spend,
    SUM(IF(channel_group = 'brand_search', clicks, 0)) AS brand_search_clicks,
    SUM(IF(channel_group = 'brand_search', impressions, 0)) AS brand_search_impressions,
    SUM(IF(channel_group = 'brand_search', eligible_impressions, 0)) AS brand_search_eligible_impressions,
    SUM(IF(channel_group = 'unmapped', spend, 0)) AS unmapped_spend,
    SUM(IF(is_sale_campaign, spend, 0)) AS sale_campaign_spend
  FROM `your-gcp-project.example_mmm.vw_mmm_campaign_channel`
  WHERE geo IS NOT NULL
  GROUP BY 1, 2
),

-- Spend whose region doesn't map to a geo (surfaced, never silently lost)
unmapped_geo AS (
  SELECT DATE_TRUNC(date, WEEK(MONDAY)) AS week_start, SUM(spend) AS spend
  FROM `your-gcp-project.example_mmm.vw_mmm_campaign_channel`
  WHERE geo IS NULL
  GROUP BY 1
)

SELECT
  s.week_start,
  s.geo,
  -- KPIs
  IFNULL(o.orders, 0) AS orders,
  IFNULL(o.new_customers, 0) AS new_customers,
  IFNULL(o.revenue, 0) AS revenue,
  IFNULL(o.new_customer_revenue, 0) AS new_customer_revenue,
  -- Paid media
  IFNULL(m.spend_google_convert, 0) AS spend_google_convert,
  IFNULL(m.spend_google_upper, 0) AS spend_google_upper,
  IFNULL(m.spend_meta_convert, 0) AS spend_meta_convert,
  IFNULL(m.spend_meta_upper, 0) AS spend_meta_upper,
  IFNULL(m.impressions_google_convert, 0) AS impressions_google_convert,
  IFNULL(m.impressions_google_upper, 0) AS impressions_google_upper,
  IFNULL(m.impressions_meta_convert, 0) AS impressions_meta_convert,
  IFNULL(m.impressions_meta_upper, 0) AS impressions_meta_upper,
  -- Controls
  IFNULL(m.brand_search_spend, 0) AS brand_search_spend,
  IFNULL(m.brand_search_clicks, 0) AS brand_search_clicks,
  IFNULL(m.brand_search_impressions, 0) AS brand_search_impressions,
  IFNULL(m.brand_search_eligible_impressions, 0) AS brand_search_eligible_impressions,
  o.discount_depth,
  o.discounted_order_share,
  IFNULL(m.sale_campaign_spend, 0) AS sale_campaign_spend,
  IF(IFNULL(m.sale_campaign_spend, 0) > 0, 1, 0) AS sale_campaign_live,
  t.trends_index AS brand_trends_index,
  -- Guardrails (the notebook asserts on these)
  IFNULL(m.unmapped_spend, 0) AS unmapped_spend,
  IFNULL(u.spend, 0) AS unmapped_geo_spend_all_geos
FROM spine s
LEFT JOIN orders_weekly o USING (week_start, geo)
LEFT JOIN media_weekly m USING (week_start, geo)
LEFT JOIN unmapped_geo u USING (week_start)
LEFT JOIN `your-gcp-project.example_mmm.mmm_google_trends_weekly` t USING (week_start, geo);
