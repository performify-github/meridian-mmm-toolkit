/* =======================================================================
   VIEW: your-gcp-project.example_mmm.vw_mmm_campaign_channel
   Generated by mmm/sql_views.py from mmm.yaml — edit the config, not this file.
   PURPOSE: Daily ads delivery, one row per campaign-day, tagged with the MMM
            channel group and geo. The only place the campaign → channel mapping
            lives: vw_mmm_weekly_geo aggregates this, and qa_campaign_channel_map.sql
            lists it for review.

   CHANNEL RULES (first match wins; patterns run on the upper-cased name):
     brand_search    Google · name pattern · minus exclusions
     google_upper    Google · objective reach, act · name pattern
     google_convert  Google
     meta_upper      Meta · objective reach, act, engage · name pattern
     meta_convert    Meta
     unmapped        anything else — a fit stops if this carries more than
                     1% of spend

   Control groups (brand_search) are controls in the model, not media.
======================================================================= */

CREATE OR REPLACE VIEW `your-gcp-project.example_mmm.vw_mmm_campaign_channel` AS

WITH base AS (
  SELECT
    date AS date,
    platform AS platform,
    campaign_id AS campaign_id,
    campaign_name AS campaign_name,
    LOWER(IFNULL(objective_type, 'unknown')) AS objective_type,
    market_region AS region,
    UPPER(campaign_name) AS n,
    IFNULL(spend, 0) AS spend,
    IFNULL(impressions, 0) AS impressions,
    IFNULL(clicks, 0) AS clicks,
    search_impression_share AS search_impression_share
  FROM `your-gcp-project.example.fact_ads_campaign_daily`
)

SELECT
  date,
  CASE
    WHEN region = 'GB' THEN 'UK'
    WHEN region = 'DE' THEN 'DE'
    WHEN region = 'FR' THEN 'FR'
    WHEN region = 'SE' THEN 'NORDICS'
    WHEN region = 'DK' THEN 'NORDICS'
    WHEN region = 'False' THEN 'NORDICS'
    WHEN region = 'FI' THEN 'NORDICS'
  END AS geo,
  platform,
  campaign_id,
  campaign_name,
  objective_type,
  CASE
    WHEN platform = 'Google' AND REGEXP_CONTAINS(n, r'BRAND ?SEARCH|BRANDED[ _]SEARCH|^BRAND \|') AND NOT REGEXP_CONTAINS(n, r'PMAX|P\.MAX|SHOPPING|DEMAND ?GEN|YOUTUBE|VIDEO|CTV')
      THEN 'brand_search'
    WHEN platform = 'Google' AND (objective_type IN ('reach', 'act') OR REGEXP_CONTAINS(n, r'YOUTUBE|TRUEVIEW|DEMAND ?GEN|VIDEO|CTV|AWARENESS'))
      THEN 'google_upper'
    WHEN platform = 'Google'
      THEN 'google_convert'
    WHEN platform = 'Meta' AND (objective_type IN ('reach', 'act', 'engage') OR REGEXP_CONTAINS(n, r'\| ?(REACH|AWARENESS) ?\|'))
      THEN 'meta_upper'
    WHEN platform = 'Meta'
      THEN 'meta_convert'
    ELSE 'unmapped'
  END AS channel_group,
  -- Sale / promotion campaigns, read from the name (feeds the sale_campaign_live control)
  REGEXP_CONTAINS(n, r'BFCM|BLACK ?FRIDAY|CYBER|WINTER SALE|SUMMER SALE|\|SALE\|') AS is_sale_campaign,
  spend,
  impressions,
  clicks,
  -- Eligible impressions ≈ the query volume a search campaign could have shown on.
  -- Impression share below 10% is reported as ~0.0999, so it is floored at 0.1.
  IF(search_impression_share > 0,
     impressions / GREATEST(search_impression_share, 0.1),
     impressions) AS eligible_impressions
FROM base;
